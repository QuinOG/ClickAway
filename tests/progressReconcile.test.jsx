import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { applyProgressResponse, beginProgressRequest, settleProgressMutation, startNewProgressSession } from '../src/app/progressResponseGuard.js'
import { fetchCurrentUser } from '../src/services/clickAwayHttpApiClient.js'
vi.mock('../src/services/clickAwayHttpApiClient.js', () => ({ fetchCurrentUser: vi.fn() }))
vi.mock('react-hot-toast', () => ({ default: { error: vi.fn() } }))
beforeEach(() => { vi.useFakeTimers(); startNewProgressSession(); vi.clearAllMocks() })
afterEach(() => { startNewProgressSession(); vi.useRealTimers() })
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r }); return { promise, resolve } }
test('trailing read converges old coins 10 after new 20 and debounces repeated settlements', async () => {
  const apply = vi.fn()
  await applyProgressResponse(beginProgressRequest(), { coins: 20, snapshotAtMs: 200 }, apply)
  await applyProgressResponse(beginProgressRequest(), { coins: 10, snapshotAtMs: 300 }, apply)
  fetchCurrentUser.mockResolvedValue({ progress: { coins: 20, snapshotAtMs: 400 } })
  settleProgressMutation(beginProgressRequest(), apply)
  await vi.advanceTimersByTimeAsync(200)
  settleProgressMutation(beginProgressRequest(), apply)
  settleProgressMutation(beginProgressRequest(), apply)
  await vi.advanceTimersByTimeAsync(299)
  expect(fetchCurrentUser).not.toHaveBeenCalled()
  await vi.advanceTimersByTimeAsync(1)
  expect(fetchCurrentUser).toHaveBeenCalledOnce()
  expect(apply).toHaveBeenLastCalledWith({ coins: 20, snapshotAtMs: 400 })
})
test('session changes and later settlements invalidate in-flight reconciliation', async () => {
  const apply = vi.fn(); const read = deferred()
  fetchCurrentUser.mockReturnValueOnce(read.promise)
  settleProgressMutation(beginProgressRequest(), apply)
  await vi.advanceTimersByTimeAsync(300)
  startNewProgressSession()
  read.resolve({ progress: { coins: 99 } }); await Promise.resolve(); await Promise.resolve()
  expect(apply).not.toHaveBeenCalled()
})
test('refresh statuses describe actual application and session changes', async () => {
  const apply = vi.fn()
  fetchCurrentUser.mockResolvedValueOnce({})
  expect(await applyProgressResponse(beginProgressRequest(), null, apply)).toBe('refresh-failed')
  const read = deferred(); fetchCurrentUser.mockReturnValueOnce(read.promise)
  const response = applyProgressResponse(beginProgressRequest(), null, apply)
  startNewProgressSession(); read.resolve({ progress: { coins: 20 } })
  expect(await response).toBe('other-session')
  fetchCurrentUser.mockResolvedValueOnce({ progress: { coins: 20 } })
  expect(await applyProgressResponse(beginProgressRequest(), null, apply)).toBe('refreshed')
  expect(apply).toHaveBeenCalledOnce()
})
